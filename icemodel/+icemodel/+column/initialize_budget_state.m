function [ledger, solid_p, liquid_p, phase_solid, phase_liquid, ...
      vapor_solid, vapor_liquid] = initialize_budget_state()
   %INITIALIZE_BUDGET_STATE Return a zeroed ledger and its substep handoffs.
   %
   %  ledger = icemodel.column.initialize_budget_state()
   %  [ledger, solid_p, liquid_p, phase_solid, phase_liquid, vapor_solid, ...
   %     vapor_liquid] = icemodel.column.initialize_budget_state()
   %
   % The optional outputs are the zeroed handoffs that the accumulators pass to
   % each other within a substep. accumulate_phase_budget produces solid_p and
   % liquid_p for accumulate_vapor_budget. Both produce the signed increments
   % that accumulate_remesh_budget needs to close gross storage. These outputs
   % are not ledger fields, and the first substep overwrites them. They are
   % returned here to give the solver its codegen predeclarations.
   %
   % Storage, phase, vapor, and remesh changes are positive into the column.
   % Overflow and merge export are positive out; unapplied vapor retains
   % rejected-input sign.
   %
   % Codegen builds the struct from the field list written out below, so the
   % order here is what the kernel compiles against. budgetoutputs holds the
   % same names for the output and retiming code.
   %
   %#codegen

   % Declare every field literally so MATLAB Coder never has to construct or
   % extend the ledger from runtime field names.
   ledger = struct( ...
      'mass_budget_solid_start_mwe', 0.0, ...
      'mass_budget_liquid_start_mwe', 0.0, ...
      'mass_budget_solid_end_mwe', 0.0, ...
      'mass_budget_liquid_end_mwe', 0.0, ...
      'mass_budget_phase_solid_mwe', 0.0, ...
      'mass_budget_phase_liquid_mwe', 0.0, ...
      'mass_budget_vapor_solid_mwe', 0.0, ...
      'mass_budget_vapor_liquid_mwe', 0.0, ...
      'mass_budget_remesh_solid_mwe', 0.0, ...
      'mass_budget_remesh_liquid_mwe', 0.0, ...
      'mass_budget_remesh_enthalpy_j_m2', 0.0, ...
      'mass_budget_cloned_bottom_solid_mwe', 0.0, ...
      'mass_budget_cloned_bottom_liquid_mwe', 0.0, ...
      'mass_budget_cloned_bottom_enthalpy_j_m2', 0.0, ...
      'mass_budget_merge_export_solid_mwe', 0.0, ...
      'mass_budget_merge_export_liquid_mwe', 0.0, ...
      'mass_budget_merge_export_enthalpy_j_m2', 0.0, ...
      'mass_budget_vapor_potential_j_m2', 0.0, ...
      'mass_budget_condensation_overflow_mwe', 0.0, ...
      'mass_budget_unapplied_vapor_j_m2', 0.0, ...
      'mass_budget_top_deletion_count', 0.0, ...
      'mass_budget_top_deletion_height_m', 0.0, ...
      'mass_budget_top_export_solid_mwe', 0.0, ...
      'mass_budget_top_export_liquid_mwe', 0.0, ...
      'mass_budget_interior_merge_count', 0.0, ...
      'mass_budget_solid_storage_gross_mwe', 0.0, ...
      'mass_budget_liquid_storage_gross_mwe', 0.0, ...
      'mass_budget_phase_solid_gross_mwe', 0.0, ...
      'mass_budget_phase_liquid_gross_mwe', 0.0, ...
      'mass_budget_vapor_solid_gross_mwe', 0.0, ...
      'mass_budget_vapor_liquid_gross_mwe', 0.0, ...
      'mass_budget_remesh_solid_gross_mwe', 0.0, ...
      'mass_budget_remesh_liquid_gross_mwe', 0.0, ...
      'mass_budget_remesh_enthalpy_gross_j_m2', 0.0, ...
      'mass_budget_cloned_bottom_solid_gross_mwe', 0.0, ...
      'mass_budget_cloned_bottom_liquid_gross_mwe', 0.0, ...
      'mass_budget_cloned_bottom_enthalpy_gross_j_m2', 0.0, ...
      'mass_budget_merge_export_solid_gross_mwe', 0.0, ...
      'mass_budget_merge_export_liquid_gross_mwe', 0.0, ...
      'mass_budget_merge_export_enthalpy_gross_j_m2', 0.0, ...
      'mass_budget_vapor_potential_gross_j_m2', 0.0, ...
      'mass_budget_condensation_overflow_gross_mwe', 0.0, ...
      'mass_budget_unapplied_vapor_gross_j_m2', 0.0);

   % Zeroed handoffs between the accumulators within one substep.
   solid_p = 0.0;
   liquid_p = 0.0;
   phase_solid = 0.0;
   phase_liquid = 0.0;
   vapor_solid = 0.0;
   vapor_liquid = 0.0;
end
