   verifyEmpty(testCase, strfind(builder_source, ...
      "cumulative surface mass loss (exported at top removal)"))
   verifySubstring(testCase, builder_source, ...
      "min(bound_a, bound_b)")
   verifySubstring(testCase, builder_source, ...
      "max(bound_a, bound_b)")
   verifyFalse(testCase, contains(builder_source, ...
      "whole-column solid-storage loss"))
   verifyFalse(testCase, contains(builder_source, "cummax("))
   verifyFalse(testCase, contains(builder_source, ...
      "model_layer_change = maskSeasonalSeries"))
   verifyFalse(testCase, contains(builder_source, ...
      "Observation support; markers are not joined"))
   verifyFalse(testCase, contains(builder_source, ...
      "Secondary H_{grid} diagnostic"))
   verifySubstring(testCase, builder_source, ...
      "[38, 59], 'stable'")
   verifyFalse(testCase, contains(builder_source, "%#ok<AGROW>"))
   verifyFalse(testCase, contains(builder_source, "isKanSite"))
   verifyFalse(testCase, contains(builder_source, "KAN_M/KAN_L"))
   verifySubstring(testCase, builder_source, ...
      "Completed site-years: model versus observation")
    verifySubstring(testCase, builder_source, ...
       "Window closure and per-step acceptance")
    verifySubstring(testCase, builder_source, ...
       "Maximum ratio to comparison signal G")
   verifyFalse(testCase, contains(builder_source, ...
      "Supplemental snow-data inventory"))
   verifySubstring(testCase, builder_source, ...
      "icemodel.verification.helpers.shellQuote")
   verifyFalse(testCase, contains(builder_source, ...
      "function quoted = shellQuote"))

