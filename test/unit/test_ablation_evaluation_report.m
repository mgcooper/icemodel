      "tiledlayout(fig, 2, 1")
   verifyFalse(testCase, contains(builder_source, "yyaxis"))
   verifySubstring(testCase, builder_source, "model_surface_mass_loss_mwe")
   verifySubstring(testCase, builder_source, "rebaseSeasonalSeries")
